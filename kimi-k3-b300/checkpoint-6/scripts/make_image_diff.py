"""Generate patches/overlay-vllm-vs-49cb2bbf.diff and prove the base.

Rule of the overlay: an overlay file = the image file plus inserted lines that carry the tag "# PERFBOT", plus the
tagged replacements recorded in patches/image-replaced-lines.json (each listed, exact text).
This script, for every overlay/vllm/**/*.py file:
  1. reverses every recorded replacement (the overlay block must occur exactly once; it becomes the base block);
  2. strips the tagged lines -> the base text;
  3. checks sha256(base) against patches/image-base-sha256.json (recorded from the served image);
  4. writes one unified diff (base -> overlay) per file into patches/overlay-vllm-vs-49cb2bbf.diff.
Exit 1 when a base hash is missing or differs, when a recorded block is not found exactly once or has an untagged new
line, when a recorded entry names a file not in the overlay, or when a diff removes a line that no recorded replacement names.

    python3 scripts/make_image_diff.py            # write the diff
    python3 scripts/make_image_diff.py --check    # only verify, write nothing
"""
from __future__ import annotations

import difflib
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OVERLAY = ROOT / "overlay"
BASES = ROOT / "patches" / "image-base-sha256.json"
OUT = ROOT / "patches" / "overlay-vllm-vs-49cb2bbf.diff"
TAG = "# PERFBOT"
REPLACED = ROOT / "patches" / "image-replaced-lines.json"


def strip(text: str) -> str:
    return "".join(line for line in text.splitlines(True) if TAG not in line)


def unreplace(rel: str, text: str, entries: list[dict]) -> tuple[str, int, list[str]]:
    """Reverse the recorded replacements of one file: the text, the count of base lines the overlay removes, the errors."""
    errors, removed = [], 0
    for e in entries:
        over, base = e["overlay"], e["base"]
        if any(TAG not in line for line in over if line not in base):
            errors.append(f"recorded block has an untagged new line {rel}")
        block = "".join(line + "\n" for line in over)
        if text.count(block) != 1:
            errors.append(f"recorded block found {text.count(block)} times {rel}")
            continue
        text = text.replace(block, "".join(line + "\n" for line in base))
        removed += sum(1 for line in base if line not in over)
    return text, removed, errors


def main() -> int:
    check = "--check" in sys.argv
    ref = json.loads(BASES.read_text())["files"]
    replaced = json.loads(REPLACED.read_text())["files"] if REPLACED.exists() else {}
    seen = set()
    bad = 0
    chunks = []
    for path in sorted(OVERLAY.glob("vllm/**/*.py")):
        rel = path.relative_to(OVERLAY).as_posix()
        text = path.read_text()
        seen.add(rel)
        unrep, allowed, errors = unreplace(rel, text, replaced.get(rel, []))
        for err in errors:
            print("FAIL", err)
            bad += 1
        base = strip(unrep)
        digest = hashlib.sha256(base.encode()).hexdigest()
        want = ref.get(rel)
        if want is None:
            print("FAIL no recorded image hash", rel)
            bad += 1
        elif not digest.startswith(want["sha256"]):
            print("FAIL base differs from image", rel, digest[:12], want["sha256"][:12])
            bad += 1
        a, b = base.splitlines(True), text.splitlines(True)
        removed = sum(1 for line in difflib.ndiff(a, b) if line.startswith("- "))
        if removed != allowed:
            print("FAIL diff removes lines", rel, removed, "recorded", allowed)
            bad += 1
        added = len(b) - len(a)
        print(f"OK   {rel} +{added}" + (f" (recorded replacement of {allowed} base lines)" if allowed else ""))
        if added or allowed:
            chunks.append("".join(difflib.unified_diff(a, b, f"a/{rel}", f"b/{rel}", n=3)))
    for rel in sorted(set(replaced) - seen):
        print("FAIL recorded replacement for a file not in the overlay", rel)
        bad += 1
    if bad:
        print("RESULT FAIL", bad)
        return 1
    if not check:
        header = ("# Unified diff: vLLM 49cb2bbf (image files) -> overlay/vllm (the served tree of patches/served-overlay-identity.json).\n"
                  "# Generated by scripts/make_image_diff.py. Every added line carries '# PERFBOT'; every removed line is a\n"
                  "# recorded replacement in patches/image-replaced-lines.json.\n"
                  "# Apply: cd <vllm site-packages>/.. && patch -p1 < this file (or run the overlay as is).\n")
        OUT.write_text(header + "".join(chunks))
        print("WROTE", OUT.relative_to(ROOT), len(chunks), "files")
    print("RESULT PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
